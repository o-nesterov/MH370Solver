	 if (pPingTime_) delete pPingTime_;
	 if (pBTO_) delete pBTO_;
	 if (pBFO_) delete pBFO_;
	 if (pDist_) delete pDist_;
	 if (pChannelType_) delete pChannelType_;

	 pPingTime_ = new double[NPings_+1];	// Ping times (seconds since 2014-03-07 00:00:00 UTC)
	 pBTO_ = new double[NPings_+1];			// BTO (microseconds)
	 pBFO_ = new double[NPings_+1];			// BFO (Hz)
	 pDist_ = new double[NPings_+1];	    // Satellite to aircraft distance (m)
	 pChannelType_ = new int[NPings_+1];	// Channel type (see above)

	 for (unsigned long i=0; i<NPings_; i++)
	 {
		 pPingTime_[i] = Pings[i][0];
		 pBTO_[i] = Pings[i][3];
		 pBFO_[i] = Pings[i][2];
		 pChannelType_[i] = (int)(Pings[i][1]);
	 }

// ----------------------------------------------------------------
//	calculate distance from the satellite to the aircraft 

	 for (unsigned long i=0; i<NPings_; i++)
	 {
		 double bto_bias = 0.0;
		 double satXYZ[3];

		// Channel Type:
		// CH_TYPE_R_RX1200 = R-Channel RX 1200; 
		// CH_TYPE_R_RX600  = R-Channel RX 600; 
		// CH_TYPE_T_RX1200 = T-Channel RX; 
		// CH_TYPE_C_RX1200 = C-Channel RX;
		// CH_TYPE_ANAMALOUS = Anamalous (R-Channel RX 1200)

		 switch(pChannelType_[i])
		 {
		 case CH_TYPE_R_RX1200:
			 bto_bias = BTO_Bias_RX1200_;
			 break;
		 case CH_TYPE_R_RX600:
			 bto_bias = BTO_Bias_RX600_;
			 break;
		 case CH_TYPE_T_RX1200:
			 bto_bias = BTO_Bias_TX_;
			 break;
		 case CH_TYPE_C_RX1200:
			 bto_bias = 0.0; // not measured for C channel
			 break;
		 case CH_TYPE_ANAMALOUS:
			 bto_bias = 0.0; // anamalous values - distance can't be inferred
			 break;
		 }

		 // get position of Inmarast's satellite
		 GetInmarsatPos(satXYZ[0], satXYZ[1], satXYZ[2], pPingTime_[i]);

		 double range_sat_to_Perth = sqrt((satXYZ[0]-Perth_XYZ_[0])*(satXYZ[0]-Perth_XYZ_[0])+
										  (satXYZ[1]-Perth_XYZ_[1])*(satXYZ[1]-Perth_XYZ_[1])+
										  (satXYZ[2]-Perth_XYZ_[2])*(satXYZ[2]-Perth_XYZ_[2]));

		 if (pChannelType_[i]==CH_TYPE_R_RX1200 || pChannelType_[i]==CH_TYPE_R_RX600 || pChannelType_[i]==CH_TYPE_T_RX1200)
		 {
			 // distance from the satellite to aircraft (see ATSB, 2014; Ashton et al., 2015)
			 pDist_[i] = (pBTO_[i]-bto_bias)*0.000001*Speed_of_light_/2.0 - range_sat_to_Perth;
		 }
		 else
		 {
			 pDist_[i] = -1.0E+10;	// distance cannot be calculated (either C-Channel or anamalous BTO values)
		 }
	 }

