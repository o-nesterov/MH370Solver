////////////////////////////////////////////////////////////////////////////////////////
// Get Inmarsat ping data: 
// t - time stamp (seconds since 2014-03-07 00:00:00 UTC), 
// dist - satellite to aircraft distance (m),
// bto (microseconds), 
// bfo (Hz),
// channel type (0 = R-Channel RX 1200; 1 = R-Channel RX 600;  2 = T-Channel RX; 3 = C-Channel RX; 4 - anamalous data / unknown how to interpret),
// n - is the sample number
bool CMH370InmarsatData::GetPingData(double& t, double& dist, double& bto, double& bfo, int& channelType, unsigned long n)
{
	if ( n>= NPings_)
	{
		if (fileout_) fprintf(fileout_, "Ping no. must be smaller than %d. \n", NPings_);
		return false;
	}

	t = pPingTime_[n];
	dist = pDist_[n];
	bto = pBTO_[n];
	bfo = pBFO_[n];
	channelType = pChannelType_[n];

	return true;
}


////////////////////////////////////////////////////////////////////////////////////////
// Get Inmarsat ping time (similar to above, but only time is returned back): 
// t - time stamp (seconds since 2014-03-07 00:00:00 UTC), 
// n - is the sample number
bool CMH370InmarsatData::GetPingData(double& t, unsigned long n)
{
	if ( n>= NPings_)
	{
		if (fileout_) fprintf(fileout_, "Ping no. must be smaller than %d. \n", NPings_);
		return false;
	}

	t = pPingTime_[n];

	return true;
}


////////////////////////////////////////////////////////////////////////////////////////
// Return the total number of available pings
unsigned long CMH370InmarsatData::GetNumberOfPings()
{
	return NPings_;
}




